-- Production rollout patch, applied to Supabase project SSC-Practice-App on 2026-10-25.
-- Creates private diagnostics, a pending-only bridge, and a bridge schedule.
-- This does not alter existing production ingestion/verification jobs.

create table if not exists public.ca_adapter_diagnostic_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  dry_run boolean not null default true,
  checked_sources integer not null default 0,
  staged integer not null default 0,
  report jsonb not null default '[]'::jsonb
);
alter table public.ca_adapter_diagnostic_runs enable row level security;

create or replace function public.ca_bridge_web_candidates_production(p_limit integer default 40)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_inserted integer := 0;
  v_eligible integer := 0;
begin
  if session_user not in ('postgres','supabase_admin') then
    raise exception 'production candidate bridge is restricted to the production scheduler';
  end if;
  select count(*) into v_eligible
  from public.ca_web_adapter_candidates c
  join public.ca_sources s on s.source_key = c.source_key
  where s.enabled = true and s.integration_type = 'web_adapter'
    and c.status = 'needs_review' and c.source_key <> 'PIB_HI'
    and lower(split_part(c.article_url, '/', 1)) = 'https:'
    and split_part(c.article_url, '/', 3) !~ '[:@]'
    and exists (
      select 1 from unnest(string_to_array(coalesce(s.allowed_host,''), ',')) as h(hostname)
      where lower(regexp_replace(btrim(h.hostname), '^www\.', '')) =
            lower(regexp_replace(split_part(c.article_url, '/', 3), '^www\.', ''))
    )
    and char_length(btrim(c.headline)) between 15 and 400
    and c.headline !~ '[ऀ-ॿ]'
    and char_length(btrim(coalesce(c.description,''))) >= 30
    and c.published_at between now()-interval '8 days' and now()+interval '2 hours'
    and not exists (select 1 from public.ca_items i where i.canonical_url = c.article_url);
  with eligible as (
    select c.*, s.id as valid_source_id, s.source_name as valid_source_name, s.category as valid_category
    from public.ca_web_adapter_candidates c
    join public.ca_sources s on s.source_key = c.source_key
    where s.enabled = true and s.integration_type = 'web_adapter'
      and c.status = 'needs_review' and c.source_key <> 'PIB_HI'
      and lower(split_part(c.article_url, '/', 1)) = 'https:'
      and split_part(c.article_url, '/', 3) !~ '[:@]'
      and exists (
        select 1 from unnest(string_to_array(coalesce(s.allowed_host,''), ',')) as h(hostname)
        where lower(regexp_replace(btrim(h.hostname), '^www\.', '')) =
              lower(regexp_replace(split_part(c.article_url, '/', 3), '^www\.', ''))
      )
      and char_length(btrim(c.headline)) between 15 and 400
      and c.headline !~ '[ऀ-ॿ]'
      and char_length(btrim(coalesce(c.description,''))) >= 30
      and c.published_at between now()-interval '8 days' and now()+interval '2 hours'
      and not exists (select 1 from public.ca_items i where i.canonical_url = c.article_url)
    order by c.published_at desc, c.id desc
    limit least(greatest(coalesce(p_limit,40),1),100)
  ),
  inserted as (
    insert into public.ca_items
      (canonical_url,source_name,headline_en,summary_en,published_at,event_date,
       topics,status,evidence_checked,source_id,exam_category,review_notes)
    select c.article_url,c.valid_source_name,btrim(c.headline),left(btrim(c.description),2000),
           c.published_at,(c.published_at at time zone 'Asia/Kolkata')::date,
           array[c.valid_category]::text[],'pending',false,c.valid_source_id,
           c.valid_category,
           format('Web adapter candidate %s (%s). Official source and facts must be independently verified before approval.',c.id,c.source_key)
    from eligible c
    on conflict (canonical_url) do nothing
    returning id
  )
  select count(*) into v_inserted from inserted;
  return jsonb_build_object('inserted_pending',v_inserted,
    'remaining_eligible',greatest(0,v_eligible-v_inserted),'auto_published',0,'ran_at',now());
end;
$function$;

revoke all on function public.ca_bridge_web_candidates_production(integer) from public, anon, authenticated;
grant execute on function public.ca_bridge_web_candidates_production(integer) to postgres, supabase_admin;

do $block$
begin
  if not exists (select 1 from cron.job where jobname='jd-ca-bridge-web-candidates-production') then
    perform cron.schedule('jd-ca-bridge-web-candidates-production','4,19,34,49 * * * *',
      'select public.ca_bridge_web_candidates_production(40);');
  end if;
end;
$block$;